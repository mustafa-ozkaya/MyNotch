struct ClipboardContentRulesTests {
    @Test(arguments: ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"])
    func privacyMarkersAreIgnored(marker: String) {
        #expect(ClipboardContentRules.shouldIgnore(types: [.string, NSPasteboard.PasteboardType(marker)]))
    }

    @Test func plainTextIsAccepted() {
        #expect(!ClipboardContentRules.shouldIgnore(types: [.string]))
        #expect(!ClipboardContentRules.shouldIgnore(types: [.string], sourceApp: "com.apple.TextEdit"))
    }

    @Test(arguments: ["com.apple.Passwords", "com.apple.Passwords.MenuBarExtra", "com.apple.keychainaccess"])
    func passwordAppsAreIgnoredWithoutMarkers(app: String) {
        #expect(ClipboardContentRules.shouldIgnore(types: [.string], sourceApp: app))
    }

    @Test func filesComeFirstThenTextThenImage() {
        #expect(ClipboardContentRules.readOrder(types: [.tiff, .string, .fileURL]) == [.files, .text, .image])
    }

    @Test func officeStyleCopyPrefersTextOverItsPicture() {
        #expect(ClipboardContentRules.readOrder(types: [.png, .pdf, .rtf, .string]) == [.text, .image])
    }

    @Test func imageOnlyCopyReadsTheImage() {
        #expect(ClipboardContentRules.readOrder(types: [.png]) == [.image])
        #expect(ClipboardContentRules.readOrder(types: [NSPasteboard.PasteboardType("com.example.custom")]).isEmpty)
    }

    @Test func pngInputIsKeptAndThumbnailIsSmall() throws {
        let png = try #require(TestImages.png(width: 400, height: 200))
        let result = try #require(ClipboardContentRules.pngAndThumbnail(from: png, isAlreadyPNG: true))

        #expect(result.png == png)
        let thumbnail = try #require(result.thumbnail)
        let size = try #require(TestImages.pixelSize(of: thumbnail))
        #expect(max(size.width, size.height) <= CGFloat(ClipboardContentRules.thumbnailMaxPixelSize))
    }

    @Test func tiffInputIsConvertedToPNG() throws {
        let png = try #require(TestImages.png(width: 50, height: 50))
        let tiff = try #require(NSImage(data: png)?.tiffRepresentation)
        let result = try #require(ClipboardContentRules.pngAndThumbnail(from: tiff, isAlreadyPNG: false))
        #expect(TestImages.isPNG(result.png))
    }
}

/// Uses a private named pasteboard, so the real clipboard is never touched.
@MainActor
final class ClipboardMonitorTests {
    let directory = FileManager.default.temporaryDirectory
        .appendingPathComponent("ClipboardMonitorTests-\(UUID().uuidString)", isDirectory: true)
    let pasteboard = NSPasteboard(name: NSPasteboard.Name("MyNotchTests-\(UUID().uuidString)"))
    lazy var store = ClipboardStore(directory: directory, limit: 50)
    lazy var monitor = ClipboardMonitor(store: store, pasteboard: pasteboard)

    deinit {
        pasteboard.releaseGlobally()
        try? FileManager.default.removeItem(at: directory)
    }

    @Test func newTextIsRecorded() {
        _ = monitor
        pasteboard.clearContents()
        pasteboard.setString("hello", forType: .string)

        monitor.checkForChanges()

        #expect(store.entries.map(\.text) == ["hello"])
    }

    @Test func unchangedPasteboardIsNotRecordedAgain() {
        _ = monitor
        pasteboard.clearContents()
        pasteboard.setString("once", forType: .string)

        monitor.checkForChanges()
        monitor.checkForChanges()

        #expect(store.entries.count == 1)
    }

    @Test func concealedCopyIsNotRecorded() {
        _ = monitor
        let item = NSPasteboardItem()
        item.setString("secret", forType: .string)
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        pasteboard.clearContents()
        pasteboard.writeObjects([item])

        monitor.checkForChanges()

        #expect(store.entries.isEmpty)
    }

    @Test func copyFromPasswordsAppIsNotRecorded() {
        monitor.frontmostAppBundleID = { "com.apple.Passwords" }
        pasteboard.clearContents()
        pasteboard.setString("hunter2", forType: .string)

        monitor.checkForChanges()

        #expect(store.entries.isEmpty)
    }

    @Test func fileCopyIsRecordedAsFiles() {
        _ = monitor
        pasteboard.clearContents()
        pasteboard.writeObjects([URL(fileURLWithPath: "/tmp/a.txt") as NSURL, URL(fileURLWithPath: "/tmp/b.txt") as NSURL])

        monitor.checkForChanges()

        #expect(store.entries.first?.kind == .files)
        #expect(store.entries.first?.filePaths == ["/tmp/a.txt", "/tmp/b.txt"])
    }

    @Test func richTextFallsBackToPlainText() throws {
        _ = monitor
        let rtf = try #require(NSAttributedString(string: "Bold words").rtf(from: NSRange(location: 0, length: 10)))
        pasteboard.clearContents()
        pasteboard.setData(rtf, forType: .rtf)

        monitor.checkForChanges()

        #expect(store.entries.first?.text == "Bold words")
    }

    @Test func imageCopyIsRecordedWithThumbnail() async throws {
        _ = monitor
        let png = try #require(TestImages.png(width: 300, height: 300))
        pasteboard.clearContents()
        pasteboard.setData(png, forType: .png)

        monitor.checkForChanges()
        // Conversion runs off the main thread; wait for it to land.
        for _ in 0..<50 where store.entries.isEmpty {
            try await Task.sleep(for: .milliseconds(20))
        }

        let entry = try #require(store.entries.first)
        #expect(entry.kind == .image)
        #expect(entry.thumbFile != nil)
    }

    @Test func copyBackIsNotRecordedAsANewCopy() throws {
        _ = monitor
        pasteboard.clearContents()
        pasteboard.setString("first", forType: .string)
        monitor.checkForChanges()
        pasteboard.clearContents()
        pasteboard.setString("second", forType: .string)
        monitor.checkForChanges()
        let first = try #require(store.entries.last)

        #expect(ClipboardActions.copyBack(first, store: store, pasteboard: pasteboard))
        monitor.noteSelfWrite()
        monitor.checkForChanges()

        #expect(store.entries.count == 2)
        #expect(pasteboard.string(forType: .string) == "first")
    }

    @Test func copyBackWritesEachKind() throws {
        _ = monitor
        let text = try #require(store.insert(ClipboardCandidate(content: .text("plain"))))
        #expect(ClipboardActions.copyBack(text, store: store, pasteboard: pasteboard))
        #expect(pasteboard.string(forType: .string) == "plain")

        let files = try #require(store.insert(ClipboardCandidate(content: .files(["/tmp/x.txt"]))))
        #expect(ClipboardActions.copyBack(files, store: store, pasteboard: pasteboard))
        let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]
        #expect(urls?.map(\.path) == ["/tmp/x.txt"])

        let png = try #require(TestImages.png(width: 10, height: 10))
        let image = try #require(store.insert(ClipboardCandidate(content: .image(png: png, thumbnailPNG: nil))))
        store.flush()
        #expect(ClipboardActions.copyBack(image, store: store, pasteboard: pasteboard))
        #expect(pasteboard.data(forType: .png) == png)
    }
}

enum TestImages {
    static func png(width: Int, height: Int) -> Data? {
        guard let context = CGContext(
            data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: 0,
            space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue
        ) else { return nil }
        context.setFillColor(CGColor(red: 0.2, green: 0.5, blue: 0.9, alpha: 1))
        context.fill(CGRect(x: 0, y: 0, width: width, height: height))
        return context.makeImage().flatMap(ClipboardContentRules.encodePNG)
    }

    static func pixelSize(of data: Data) -> CGSize? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else { return nil }
        return CGSize(width: image.width, height: image.height)
    }

    static func isPNG(_ data: Data) -> Bool {
        data.starts(with: [0x89, 0x50, 0x4E, 0x47])
    }
}
