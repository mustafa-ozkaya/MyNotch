import AppKit
import ImageIO
import UniformTypeIdentifiers

/// Pure decisions about pasteboard contents, separated from the monitor so they can be unit-tested.
enum ClipboardContentRules {
    /// Markers apps (password managers, Keychain, etc.) put on copies that shouldn't be recorded.
    /// See nspasteboard.org.
    static let privacyMarkers: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    static let textTypes: Set<NSPasteboard.PasteboardType> = [
        .string, .rtf, .rtfd, .html,
        NSPasteboard.PasteboardType("public.utf8-plain-text"),
    ]

    static let imageTypes: Set<NSPasteboard.PasteboardType> = [
        .png, .tiff,
        NSPasteboard.PasteboardType(UTType.jpeg.identifier),
        NSPasteboard.PasteboardType(UTType.heic.identifier),
    ]

    /// Apps whose copies are never recorded. Apple's Passwords app doesn't set the nspasteboard.org
    /// markers (it only clears the clipboard later), so it's recognized by bundle ID instead.
    /// Prefix match, so it also covers e.g. the Passwords menu bar extra.
    static let ignoredSourceAppPrefixes = [
        "com.apple.Passwords",
        "com.apple.keychainaccess",
    ]

    /// True if the copy must not be recorded: it carries a privacy marker, or it came from a password app.
    static func shouldIgnore(types: [NSPasteboard.PasteboardType], sourceApp: String? = nil) -> Bool {
        if types.contains(where: privacyMarkers.contains) {
            return true
        }
        guard let sourceApp else { return false }
        return ignoredSourceAppPrefixes.contains { sourceApp.hasPrefix($0) }
    }

    /// The kinds to try reading, in order. Files come first. Text comes before images because
    /// Office/iWork apps put a picture of the selection next to copied text; the image is the
    /// fallback when there's no usable text (e.g. "Copy Image" in a browser).
    static func readOrder(types: [NSPasteboard.PasteboardType]) -> [ClipboardEntry.Kind] {
        var order: [ClipboardEntry.Kind] = []
        if types.contains(.fileURL) { order.append(.files) }
        if types.contains(where: textTypes.contains) { order.append(.text) }
        if types.contains(where: imageTypes.contains) { order.append(.image) }
        return order
    }

    // MARK: - Images

    static let thumbnailMaxPixelSize = 160

    /// Converts image data (PNG, TIFF, JPEG, HEIC…) to PNG and makes a PNG thumbnail.
    /// Uses ImageIO only, so it's safe to call off the main thread.
    static func pngAndThumbnail(from data: Data, isAlreadyPNG: Bool) -> (png: Data, thumbnail: Data?)? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }

        let png: Data
        if isAlreadyPNG {
            png = data
        } else {
            guard let image = CGImageSourceCreateImageAtIndex(source, 0, nil),
                  let encoded = encodePNG(image) else { return nil }
            png = encoded
        }

        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: thumbnailMaxPixelSize,
        ]
        let thumbnail = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary).flatMap(encodePNG)
        return (png, thumbnail)
    }

    static func encodePNG(_ image: CGImage) -> Data? {
        let output = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(output, UTType.png.identifier as CFString, 1, nil) else {
            return nil
        }
        CGImageDestinationAddImage(destination, image, nil)
        guard CGImageDestinationFinalize(destination) else { return nil }
        return output as Data
    }
}
